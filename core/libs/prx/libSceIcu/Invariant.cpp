bool Invariant(char16_t unit) {
    return unit <= 0x7f && (InvariantChars[unit >> 5] & (1u << (unit & 0x1f))) != 0;
}

std::int32_t AsciiFromEbcdicInvariant(std::uint8_t unit) {
    if (unit == 0) return 0;
    const std::uint8_t ascii = AsciiFromEbcdic[unit];
    return ascii != 0 && Invariant(ascii) ? ascii : -1;
}

std::int32_t AsciiPropertyNameChar(const char* name) {
    std::int32_t index = 0;
    char value;
    while ((value = name[index++]) == 0x2d || value == 0x5f || value == 0x20 || (value >= 0x09 && value <= 0x0d)) {}
    if (value == 0) return index << 8;
    return (index << 8) | static_cast<std::uint8_t>(uprv_asciitolower_nid_postfix(value));
}

std::int32_t EbcdicPropertyNameChar(const char* name) {
    std::int32_t index = 0;
    char value;
    while ((value = name[index++]) == 0x60 || value == 0x6d || value == 0x40 || value == 0x05 || value == 0x15 || value == 0x25 ||
           value == 0x0b || value == 0x0c || value == 0x0d) {}
    if (value == 0) return index << 8;
    return (index << 8) | static_cast<std::uint8_t>(uprv_ebcdictolower_nid_postfix(value));
}

template<class TNext>
std::int32_t ComparePropertyNames(const char* first, const char* second, TNext next) {
    if (!first || !second) APS5_INVALID_ARG_EX;
    for (;;) {
        const std::int32_t left = next(first);
        const std::int32_t right = next(second);
        if (((left | right) & 0xff) == 0) return 0;
        if (left != right) {
            const std::int32_t difference = (left & 0xff) - (right & 0xff);
            if (difference != 0) return difference;
        }
        first += left >> 8;
        second += right >> 8;
    }
}

template<class TMap>
std::uint8_t* CopyMapped(std::uint8_t* destination, const std::uint8_t* source, std::int32_t count, TMap map) {
    if (!source) APS5_INVALID_ARG_EX;
    std::int64_t remaining = count;
    if (count == -1) {
        remaining = 1;
        while (source[remaining - 1] != 0) ++remaining;
        if (remaining > std::numeric_limits<std::int32_t>::max()) throw std::overflow_error("ICU: string length exceeds int32");
    }
    if (remaining > 0 && !destination) APS5_INVALID_ARG_EX;
    std::size_t index = 0;
    while (source[index] != 0 && remaining > 0) {
        destination[index] = map(source[index]);
        ++index;
        --remaining;
    }
    while (remaining > 0) {
        destination[index++] = 0;
        --remaining;
    }
    return destination;
}

